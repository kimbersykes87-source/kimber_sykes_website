/**
 * Post-build (static export):
 *  1. Injects one JSON-LD @graph into <head> of every page (built by scripts/lib/schema-graph.mjs).
 *     Title and description are read from each page's own <title> and meta description,
 *     so schema and meta can never drift apart.
 *  2. Appends X-Robots-Tag: noindex for Next.js RSC payload files (/about.txt etc.) to out/_headers.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createSchemaBuilder } from "./lib/schema-graph.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const outDir = path.join(root, "out");
const site = (process.env.NEXT_PUBLIC_SITE_URL || "https://kimbersykes.com").replace(/\/$/, "");

const readJson = (rel) => JSON.parse(fs.readFileSync(path.join(root, rel), "utf8"));

function decodeEntities(s) {
  return s
    .replace(/&#x27;|&#39;/g, "'")
    .replace(/&quot;/g, '"')
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&amp;/g, "&");
}

function safeJsonLdStringify(data) {
  return JSON.stringify(data).replace(/</g, "\\u003c");
}

function htmlFileToRoute(relPath) {
  const normalized = relPath.replace(/\\/g, "/");
  if (normalized === "index.html") return "/";
  if (normalized.endsWith("/index.html")) return `/${normalized.slice(0, -"/index.html".length)}`;
  if (normalized.endsWith(".html")) return `/${normalized.slice(0, -".html".length)}`;
  return null;
}

function walk(dir, ext, files = []) {
  for (const name of fs.readdirSync(dir)) {
    const full = path.join(dir, name);
    if (fs.statSync(full).isDirectory()) {
      if (name === "_next" || name === "images") continue;
      walk(full, ext, files);
    } else if (name.endsWith(ext)) {
      files.push(full);
    }
  }
  return files;
}

function main() {
  if (!fs.existsSync(outDir)) {
    console.error("inject-json-ld-head: out/ not found; run next build first");
    process.exit(1);
  }

  const buildGraph = createSchemaBuilder({
    site,
    identity: readJson("data/site.json"),
    projects: readJson("data/projects.json"),
    publicDir: path.join(root, "public"),
  });

  let injected = 0;
  for (const file of walk(outDir, ".html")) {
    const route = htmlFileToRoute(path.relative(outDir, file));
    if (!route) continue;
    let html = fs.readFileSync(file, "utf8");
    // Remove any JSON-LD React may have rendered, so the head graph is the only one.
    html = html.replace(/<script type="application\/ld\+json">[\s\S]*?<\/script>/g, "");

    const title = decodeEntities((html.match(/<title>([\s\S]*?)<\/title>/) ?? [])[1] ?? "");
    const description = decodeEntities((html.match(/<meta name="description" content="([^"]*)"/) ?? [])[1] ?? "");
    const graph = buildGraph(route, { title, description });
    if (graph) {
      if (!html.includes("</head>")) throw new Error(`No </head> in ${file}`);
      html = html.replace("</head>", `<script type="application/ld+json">${safeJsonLdStringify(graph)}</script></head>`);
      injected++;
      console.log(`json-ld: ${route} -> ${graph["@graph"].length} node(s)`);
    }
    fs.writeFileSync(file, html, "utf8");
  }
  console.log(`inject-json-ld-head: updated ${injected} HTML file(s)`);

  // RSC payloads are for client-side navigation only; keep them out of search indexes.
  const keep = new Set(["llms.txt", "llms-full.txt", "robots.txt"]);
  const rsc = walk(outDir, ".txt")
    .map((f) => path.relative(outDir, f).replace(/\\/g, "/"))
    .filter((rel) => !keep.has(rel));
  if (rsc.length) {
    const headersFile = path.join(outDir, "_headers");
    const existing = fs.existsSync(headersFile) ? fs.readFileSync(headersFile, "utf8").trimEnd() + "\n\n" : "";
    const block = rsc.map((rel) => `/${rel}\n  X-Robots-Tag: noindex`).join("\n");
    fs.writeFileSync(headersFile, `${existing}# Generated by scripts/inject-json-ld-head.mjs: RSC payloads\n${block}\n`, "utf8");
    console.log(`_headers: noindex for ${rsc.length} RSC payload file(s)`);
  }
}

main();
